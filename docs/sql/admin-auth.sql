-- ============================================================
-- Matcha POS · TÀI KHOẢN QUẢN TRỊ CSDL (chỉ chủ sở hữu biết)
-- Mật khẩu lưu dạng bcrypt (pgcrypto) — KHÔNG bao giờ nằm trong mã nguồn app.
-- ============================================================
create extension if not exists pgcrypto;

create table if not exists public.admin_accounts (
  id           bigint generated by default as identity primary key,
  username     text not null unique,
  pass_hash    text not null,
  is_active    boolean not null default true,
  failed_count int not null default 0,
  locked_until timestamptz,
  last_login   timestamptz,
  created_at   timestamptz not null default now()
);

create table if not exists public.admin_sessions (
  id         bigint generated by default as identity primary key,
  token_hash text not null unique,
  username   text not null,
  expires_at timestamptz not null,
  created_at timestamptz not null default now()
);

alter table public.admin_accounts enable row level security;
alter table public.admin_sessions enable row level security;
revoke all on public.admin_accounts from anon, authenticated;
revoke all on public.admin_sessions from anon, authenticated;

-- Kiểm tra phiên quản trị còn hiệu lực?
create or replace function public.admin_check(p_token text)
returns boolean language sql stable security definer set search_path = public, extensions, pg_temp as $$
  select exists (
    select 1 from public.admin_sessions s
    where s.token_hash = encode(digest(coalesce(p_token,''), 'sha256'), 'hex')
      and s.expires_at > now()
  );
$$;

-- Đăng nhập quản trị: trả token phiên (60 phút) hoặc NULL. Khoá 15 phút sau 5 lần sai.
create or replace function public.admin_login(p_user text, p_pass text)
returns text language plpgsql security definer set search_path = public, extensions, pg_temp as $$
declare
  a public.admin_accounts;
  v_token text;
begin
  select * into a from public.admin_accounts where username = lower(trim(p_user)) limit 1;
  if a.id is null then
    perform pg_sleep(0.4);            -- chống dò tài khoản
    return null;
  end if;
  if not a.is_active then return null; end if;
  if a.locked_until is not null and a.locked_until > now() then return null; end if;

  if crypt(p_pass, a.pass_hash) <> a.pass_hash then
    update public.admin_accounts
       set failed_count = failed_count + 1,
           locked_until = case when failed_count + 1 >= 5 then now() + interval '15 minutes' else locked_until end
     where id = a.id;
    return null;
  end if;

  v_token := encode(gen_random_bytes(32), 'hex');
  insert into public.admin_sessions (token_hash, username, expires_at)
  values (encode(digest(v_token,'sha256'),'hex'), a.username, now() + interval '60 minutes');
  update public.admin_accounts set failed_count = 0, locked_until = null, last_login = now() where id = a.id;
  delete from public.admin_sessions where expires_at < now();
  return v_token;
end $$;

-- Đổi mật khẩu: cần phiên hợp lệ. (Tạo tài khoản đầu tiên thì dùng script bootstrap riêng.)
create or replace function public.admin_change_password(p_token text, p_old text, p_new text)
returns boolean language plpgsql security definer set search_path = public, extensions, pg_temp as $$
declare a public.admin_accounts;
begin
  if not public.admin_check(p_token) then return false; end if;
  select * into a from public.admin_accounts
   where username = (select s.username from public.admin_sessions s
                      where s.token_hash = encode(digest(p_token,'sha256'),'hex') limit 1);
  if a.id is null or crypt(p_old, a.pass_hash) <> a.pass_hash then return false; end if;
  if length(p_new) < 10 then return false; end if;
  update public.admin_accounts set pass_hash = crypt(p_new, gen_salt('bf', 11)) where id = a.id;
  delete from public.admin_sessions;        -- đổi mật khẩu → huỷ mọi phiên
  return true;
end $$;

-- Đăng xuất quản trị
create or replace function public.admin_logout(p_token text)
returns void language sql security definer set search_path = public, extensions, pg_temp as $$
  delete from public.admin_sessions where token_hash = encode(digest(coalesce(p_token,''),'sha256'),'hex');
$$;

grant execute on function public.admin_check(text) to anon, authenticated;
grant execute on function public.admin_login(text, text) to anon, authenticated;
grant execute on function public.admin_change_password(text, text, text) to anon, authenticated;
grant execute on function public.admin_logout(text) to anon, authenticated;
